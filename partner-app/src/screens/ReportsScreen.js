import React, { useState } from 'react';
import { View, Text, ScrollView, Pressable, StyleSheet } from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { TopBar, Panel } from '../components/kit';
import { Chip } from '../components/ui';
import { colors, fonts } from '../theme';
import { reports } from '../data/hub';
import { notify } from '../utils/platform';

const MONTHS = (() => {
  const out = [];
  const d = new Date();
  for (let i = 0; i < 4; i++) {
    const m = new Date(d.getFullYear(), d.getMonth() - i, 1);
    out.push(m.toLocaleString('en-IN', { month: 'short', year: 'numeric' }));
  }
  return out;
})();

export default function ReportsScreen() {
  const [month, setMonth] = useState(MONTHS[0]);
  return (
    <View style={{ flex: 1, backgroundColor: colors.bg }}>
      <TopBar back title="Reports" subtitle="Download for your CA and records" />
      <ScrollView contentContainerStyle={{ paddingBottom: 24 }}>
        <View style={styles.months}>
          {MONTHS.map((m) => <Chip key={m} label={m} active={month === m} onPress={() => setMonth(m)} />)}
        </View>
        <Panel style={{ marginTop: 0 }}>
          {reports.map((r, i) => (
            <View key={r.id} style={[styles.row, i === reports.length - 1 && { borderBottomWidth: 0 }]}>
              <View style={styles.icon}><Ionicons name={r.icon} size={20} color={colors.accent} /></View>
              <View style={{ flex: 1, marginLeft: 12 }}>
                <Text style={styles.title}>{r.title}</Text>
                <Text style={styles.sub}>{r.sub} · {r.period}</Text>
              </View>
              <Pressable style={styles.dl} onPress={() => notify('Report requested', `${r.title} for ${month} will be emailed to you as Excel and PDF.`)}>
                <Ionicons name="download-outline" size={18} color={colors.accent} />
              </Pressable>
            </View>
          ))}
        </Panel>
        <Text style={styles.note}>Reports are generated by the backend. This prototype shows the list sellers will see.</Text>
      </ScrollView>
    </View>
  );
}

const styles = StyleSheet.create({
  months: { flexDirection: 'row', flexWrap: 'wrap', rowGap: 8, padding: 12 },
  row: { flexDirection: 'row', alignItems: 'center', paddingVertical: 12, borderBottomWidth: 1, borderBottomColor: colors.border },
  icon: { width: 40, height: 40, borderRadius: 12, backgroundColor: colors.accentSoft, alignItems: 'center', justifyContent: 'center' },
  title: { fontSize: 14, fontWeight: '600', color: colors.black },
  sub: { fontSize: 11, color: colors.muted, marginTop: 2 },
  dl: { width: 38, height: 38, borderRadius: 19, borderWidth: 1, borderColor: colors.border, alignItems: 'center', justifyContent: 'center' },
  note: { fontSize: 11, color: colors.faint, textAlign: 'center', marginTop: 12, paddingHorizontal: 24, fontFamily: fonts.displayMedium },
});
